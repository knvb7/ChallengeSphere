-- V12: block/report persistence and notification id repair.

ALTER TABLE challengesphere.users
    ALTER COLUMN hashed_password DROP NOT NULL;

ALTER TABLE challengesphere.user_preferences
    ALTER COLUMN notify_on_glory SET DEFAULT FALSE;

-- Repair older/dev databases where notifications was created without an id column.
-- This intentionally avoids ALTER SEQUENCE ... OWNED BY so it does not hit
-- "sequence must have same owner as table it is linked to".
ALTER TABLE challengesphere.notifications
    ADD COLUMN IF NOT EXISTS id BIGINT;

CREATE SEQUENCE IF NOT EXISTS challengesphere.notifications_id_seq;

UPDATE challengesphere.notifications
SET id = nextval('challengesphere.notifications_id_seq')
WHERE id IS NULL;

SELECT setval(
    'challengesphere.notifications_id_seq',
    GREATEST(COALESCE((SELECT MAX(id) FROM challengesphere.notifications), 0), 1),
    COALESCE((SELECT MAX(id) FROM challengesphere.notifications), 0) > 0
);

ALTER TABLE challengesphere.notifications
    ALTER COLUMN id SET DEFAULT nextval('challengesphere.notifications_id_seq');

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conrelid = 'challengesphere.notifications'::regclass
          AND contype = 'p'
    ) THEN
        ALTER TABLE challengesphere.notifications
            ADD CONSTRAINT notifications_pkey PRIMARY KEY (id);
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS challengesphere.user_blocks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    blocker_user_id BIGINT NOT NULL REFERENCES challengesphere.users(id) ON DELETE CASCADE,
    blocked_user_id BIGINT NOT NULL REFERENCES challengesphere.users(id) ON DELETE CASCADE,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_user_blocks_pair UNIQUE (blocker_user_id, blocked_user_id),
    CONSTRAINT chk_user_blocks_not_self CHECK (blocker_user_id <> blocked_user_id)
);

CREATE INDEX IF NOT EXISTS idx_user_blocks_blocker_active
    ON challengesphere.user_blocks (blocker_user_id, active);

CREATE INDEX IF NOT EXISTS idx_user_blocks_blocked_active
    ON challengesphere.user_blocks (blocked_user_id, active);

CREATE TABLE IF NOT EXISTS challengesphere.user_reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporter_user_id BIGINT NOT NULL REFERENCES challengesphere.users(id) ON DELETE CASCADE,
    reported_user_id BIGINT NOT NULL REFERENCES challengesphere.users(id) ON DELETE CASCADE,
    reason VARCHAR(128) NOT NULL,
    details TEXT,
    status VARCHAR(32) NOT NULL DEFAULT 'OPEN',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_user_reports_not_self CHECK (reporter_user_id <> reported_user_id)
);

CREATE INDEX IF NOT EXISTS idx_user_reports_reported_status
    ON challengesphere.user_reports (reported_user_id, status, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_user_reports_reporter_created
    ON challengesphere.user_reports (reporter_user_id, created_at DESC);
