-- Dedicated motivation preference and durable, one-time milestone claims.

ALTER TABLE challengesphere.user_preferences
    ADD COLUMN IF NOT EXISTS notify_on_motivation BOOLEAN;

-- Existing rows inherit the effective global phone-push choice: both the dedicated global
-- preference and the legacy users.notifications push bit must be enabled.
UPDATE challengesphere.user_preferences preferences
SET notify_on_motivation = COALESCE(preferences.push_notifications_enabled, TRUE)
        AND ((COALESCE(users.notifications, 1) & 1) = 1)
FROM challengesphere.users users
WHERE preferences.user_id = users.id
  AND preferences.notify_on_motivation IS NULL;

-- Preferences were historically lazy. Materialize defaults for legacy users without a row so a
-- globally disabled user cannot silently inherit motivation alerts as enabled after this upgrade.
INSERT INTO challengesphere.user_preferences (user_id, notify_on_motivation)
SELECT users.id,
       ((COALESCE(users.notifications, 1) & 1) = 1)
FROM challengesphere.users users
WHERE NOT EXISTS (
    SELECT 1
    FROM challengesphere.user_preferences preferences
    WHERE preferences.user_id = users.id
)
ON CONFLICT (user_id) DO NOTHING;

ALTER TABLE challengesphere.user_preferences
    ALTER COLUMN notify_on_motivation SET DEFAULT TRUE,
    ALTER COLUMN notify_on_motivation SET NOT NULL;

CREATE TABLE IF NOT EXISTS challengesphere.user_challenge_milestones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES challengesphere.users(id) ON DELETE CASCADE,
    challenge_id BIGINT NOT NULL REFERENCES challengesphere.challenges(id) ON DELETE CASCADE,
    milestone_code VARCHAR(40) NOT NULL,
    notification_id BIGINT REFERENCES challengesphere.notifications(id) ON DELETE SET NULL,
    claimed_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_user_challenge_milestone UNIQUE (user_id, challenge_id, milestone_code),
    CONSTRAINT chk_user_challenge_milestone_code CHECK (
        milestone_code IN ('FINAL_STRETCH', 'FINISH_STRONG', 'TOP_THREE', 'FIRST_PLACE')
    )
);

CREATE INDEX IF NOT EXISTS idx_user_challenge_milestones_challenge
    ON challengesphere.user_challenge_milestones (challenge_id, user_id);
