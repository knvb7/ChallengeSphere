CREATE TABLE IF NOT EXISTS challengesphere.feature_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES challengesphere.users(id) ON DELETE CASCADE,
    category VARCHAR(40) NOT NULL,
    message VARCHAR(300) NOT NULL,
    app_version VARCHAR(80),
    platform VARCHAR(80),
    device_info VARCHAR(200),
    status VARCHAR(30) NOT NULL DEFAULT 'NEW',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_feature_requests_category CHECK (
        category IN ('CHALLENGES', 'COMMUNITY', 'PROGRESS_AND_STATS', 'APP_EXPERIENCE', 'OTHER')
    ),
    CONSTRAINT chk_feature_requests_message_length CHECK (
        char_length(btrim(message)) BETWEEN 10 AND 300
    ),
    CONSTRAINT chk_feature_requests_status CHECK (
        status IN ('NEW', 'REVIEWING', 'PLANNED', 'DECLINED', 'COMPLETED')
    )
);

CREATE INDEX IF NOT EXISTS idx_feature_requests_user_created
    ON challengesphere.feature_requests (user_id, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_feature_requests_status_created
    ON challengesphere.feature_requests (status, created_at DESC);
